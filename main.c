void Encoder_Init(){
    HAL_TIM_Encoder_Start(&htim4, TIM_CHANNEL_ALL);
    HAL_TIM_Encoder_Start(&htim3, TIM_CHANNEL_ALL);// Start encoder mode
}

void Read_Encoder(){
    encoder_ticks_l = __HAL_TIM_GET_COUNTER(&htim4); // LEFT MOTOR
    encoder_ticks_r = __HAL_TIM_GET_COUNTER(&htim3);// RIGHT MOTOR Store encoder ticks
}


void Set_Motor_Direction_Left(float pwm_output) {
	if (pwm_output > 0){
			HAL_GPIO_WritePin(ML_IN1_GPIO_Port, ML_IN1_Pin, GPIO_PIN_RESET );
			HAL_GPIO_WritePin(ML_IN2_GPIO_Port, ML_IN2_Pin, GPIO_PIN_SET );
			__HAL_TIM_SET_COMPARE(&htim2, TIM_CHANNEL_2, pwm_output);

	}
	else if (pwm_output < 0) {
			HAL_GPIO_WritePin(ML_IN1_GPIO_Port, ML_IN1_Pin,  GPIO_PIN_SET);
			HAL_GPIO_WritePin(ML_IN2_GPIO_Port, ML_IN2_Pin,  GPIO_PIN_RESET);
			__HAL_TIM_SET_COMPARE(&htim2, TIM_CHANNEL_2, -pwm_output);
	}

}

void Set_Motor_Direction_Right(float pwm_output) {
	if(pwm_output > 0 ){
			HAL_GPIO_WritePin(MR_IN1_GPIO_Port, MR_IN1_Pin, GPIO_PIN_RESET);
			HAL_GPIO_WritePin(MR_IN2_GPIO_Port, MR_IN2_Pin, GPIO_PIN_SET);
			__HAL_TIM_SET_COMPARE(&htim2, TIM_CHANNEL_1, pwm_output);

	}
	else if(pwm_output < 0 ){
		HAL_GPIO_WritePin(MR_IN1_GPIO_Port, MR_IN1_Pin, GPIO_PIN_SET);
		HAL_GPIO_WritePin(MR_IN2_GPIO_Port, MR_IN2_Pin, GPIO_PIN_RESET);
		__HAL_TIM_SET_COMPARE(&htim2, TIM_CHANNEL_1, -pwm_output);
	}

}

float Pid_Right(float Kp, float Ki, float Kd){
	error_r = ref_r - rpm_r;
	pwm_output_r = (Kp* error_r) + Kd *( error_r - prev_error_r) + Ki * sum_error_r;
	prev_error_r = error_r;
	sum_error_r = sum_error_r + error_r;

	if (pwm_output_r > 449) pwm_output_r = 449;
	else if (pwm_output_r < -449) pwm_output_r = -449;
	else pwm_output_r = pwm_output_r;
//	if (pwm_output_r > -50 && pwm_output_r < 50) pwm_output_r = 0;

	return pwm_output_r;
}

float Pid_Left(float Kp, float Ki, float Kd){
	error_l = ref_l - rpm_l;
	pwm_output_l = (Kp * error_l) + Kd *( error_l - prev_error_l) + Ki * sum_error_l;
	prev_error_l = error_l;
	sum_error_l = sum_error_l + error_l;

	if (pwm_output_l > 500) pwm_output_l = 500;
	else if (pwm_output_l < -500) pwm_output_l = -500;
	else pwm_output_l = pwm_output_l;
//	if (pwm_output_l > -50 && pwm_output_l < 50) pwm_output_l = 0;

	return pwm_output_l;
}

void Calculate_RPM(float* rpm_left, float* rpm_right){
    static int16_t last_count_l, last_count_r = 0;
    int16_t current_count_l  = encoder_ticks_l;
    int16_t current_count_r  = encoder_ticks_r;

    int16_t delta_count_l = current_count_l - last_count_l;
    int16_t delta_count_r = current_count_r - last_count_r;
    last_count_l = current_count_l;
    last_count_r = current_count_r;

    *rpm_left = (delta_count_l * 60.0f) / (1900 * 0.05f);  // Assuming 1800 pulses per revolution, 50ms interval
    *rpm_right = (delta_count_r * 60.0f) / (1900* 0.05f);
    delta_count_l = 0;
    delta_count_r = 0;

}

